const EDGE_BUCKETS = 64;
type Edge = readonly [x1: number, y1: number, x2: number, y2: number];

// Index the edges by their vertical span. This keeps thousands of particle
// classifications fast while preserving exact polygon tests, without rasterizing.
function indexRing(ring: MapRing) {
  const buckets: Edge[][] = Array.from({ length: EDGE_BUCKETS }, () => []);
  const minX = Math.min(...ring.map(([x]) => x));
  const maxX = Math.max(...ring.map(([x]) => x));
  const minY = Math.min(...ring.map(([, y]) => y));
  const maxY = Math.max(...ring.map(([, y]) => y));
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [x1, y1] = ring[i];
    const [x2, y2] = ring[j];
    if (y1 === y2) continue;
    const start = Math.min(EDGE_BUCKETS - 1, Math.floor(Math.min(y1, y2) * EDGE_BUCKETS));
    const end = Math.min(EDGE_BUCKETS - 1, Math.floor(Math.max(y1, y2) * EDGE_BUCKETS));
    const edge: Edge = [x1, y1, x2, y2];
    for (let bucket = start; bucket <= end; bucket++) buckets[bucket].push(edge);
  }
  return { buckets, minX, maxX, minY, maxY };
}

function pointInRing(x: number, y: number, ring: ReturnType<typeof indexRing>): boolean {
  if (x < ring.minX || x > ring.maxX || y < ring.minY || y > ring.maxY) return false;
  const edges = ring.buckets[Math.min(EDGE_BUCKETS - 1, Math.floor(y * EDGE_BUCKETS))];
  let inside = false;
  for (const edge of edges) {
    if ((edge[1] > y) !== (edge[3] > y) &&
      x < ((edge[2] - edge[0]) * (y - edge[1])) / (edge[3] - edge[1]) + edge[0]) {
      inside = !inside;
    }
  }
  return inside;
}

const indexedWater = WATER_POLYGONS.map(({ outer, holes }) => ({
  outer: indexRing(outer),
  holes: holes.map(indexRing),
}));

