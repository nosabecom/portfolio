export type MapPoint = readonly [x: number, y: number];
export type MapRing = readonly MapPoint[];
export interface WaterPolygon {
  readonly outer: MapRing;
  readonly holes: readonly MapRing[];
}

export const LAGOS_BOUNDS = {
  west: 3.18,
  south: 6.36,
  east: 3.65,
  north: 6.67,
} as const;

/** Width / height at the middle latitude, for an undistorted local map. */
export const LAGOS_ASPECT_RATIO =
  ((LAGOS_BOUNDS.east - LAGOS_BOUNDS.west) *
    Math.cos(((LAGOS_BOUNDS.north + LAGOS_BOUNDS.south) / 2) * Math.PI / 180)) /
  (LAGOS_BOUNDS.north - LAGOS_BOUNDS.south);

export const GEOGRAPHY_ATTRIBUTION = {
  text: '© OpenStreetMap contributors',
  url: 'https://www.openstreetmap.org/copyright',
  license: 'https://opendatacommons.org/licenses/odbl/1-0/',
} as const;

/** WGS84 longitude/latitude to the map's north-up unit square. */
export function projectCoordinate(longitude: number, latitude: number): MapPoint {
  return [
    (longitude - LAGOS_BOUNDS.west) / (LAGOS_BOUNDS.east - LAGOS_BOUNDS.west),
    (LAGOS_BOUNDS.north - latitude) / (LAGOS_BOUNDS.north - LAGOS_BOUNDS.south),
  ];
}

